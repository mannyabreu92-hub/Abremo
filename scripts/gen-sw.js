// Stamps sw.js with the list of files to precache and a VERSION derived from their contents, and
// index.html with modulepreload links for the app's modules.
// Runs as part of the build (scripts/write-config.js) so every deploy gets a fresh cache;
// run it yourself after changing app files: npm run gen:sw
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { posix } from 'node:path';

const ROOT = new URL('../', import.meta.url);
const read = (rel) => readFileSync(new URL(rel, ROOT));
const START = '// ——— generated by scripts/gen-sw.js — do not edit between these markers ———';
const END = '// ——— end generated ———';

function walk(dir, exts) {
  return readdirSync(new URL(dir, ROOT), { withFileTypes: true }).flatMap((d) => {
    const rel = `${dir}${d.name}`;
    if (d.isDirectory()) return walk(`${rel}/`, exts);
    return exts.some((e) => d.name.endsWith(e)) ? [rel] : [];
  });
}

/** Everything the app needs to start offline. Install-screen screenshots are not needed offline. */
export function assetList() {
  const src = walk('src/', ['.js', '.css']).sort();
  const icons = walk('icons/', ['.png']).sort();
  return ['index.html', 'manifest.webmanifest', ...src, ...icons];
}

export function contentVersion(files = assetList()) {
  const h = createHash('sha256');
  for (const f of files) h.update(f).update('\0').update(read(f)).update('\0');
  return h.digest('hex').slice(0, 12);
}

export function swSource(version = contentVersion()) {
  const sw = read('sw.js').toString('utf8');
  const a = sw.indexOf(START);
  const b = sw.indexOf(END);
  if (a < 0 || b < a) throw new Error('sw.js generated markers not found');
  const urls = ['./', ...assetList().map((f) => `./${f}`)];
  const block = `${START}\nconst VERSION = '${version}';\nconst ASSETS = ${JSON.stringify(urls, null, 2)};\n`;
  return sw.slice(0, a) + block + sw.slice(b);
}

/**
 * The app's static ES-module graph (app.js and everything it imports, transitively). The browser
 * otherwise discovers these one import at a time; listing them as modulepreload lets it fetch them
 * in parallel on the first visit.
 */
export function moduleGraph(entry = 'src/ui/app.js') {
  const seen = new Set();
  const queue = [entry];
  while (queue.length) {
    const f = queue.shift();
    if (seen.has(f)) continue;
    seen.add(f);
    const src = read(f).toString('utf8');
    for (const m of src.matchAll(/^\s*(?:import|export)\s(?:[^'";]*?\sfrom\s)?['"](\.{1,2}\/[^'"]+\.js)['"]/gm)) {
      queue.push(posix.normalize(posix.join(posix.dirname(f), m[1])));
    }
  }
  return [...seen].filter((f) => f !== entry).sort();
}

const PRELOAD_START = '<!-- modulepreload: generated by scripts/gen-sw.js -->';
const PRELOAD_END = '<!-- end modulepreload -->';
export function indexSource() {
  const html = read('index.html').toString('utf8');
  const a = html.indexOf(PRELOAD_START);
  const b = html.indexOf(PRELOAD_END);
  if (a < 0 || b < a) throw new Error('index.html modulepreload markers not found');
  const links = moduleGraph().map((f) => `  <link rel="modulepreload" href="${f}">`).join('\n');
  return `${html.slice(0, a)}${PRELOAD_START}\n${links}\n  ${html.slice(b)}`;
}

export function stampServiceWorker() {
  writeFileSync(new URL('index.html', ROOT), indexSource()); // first: index.html is part of the version
  const version = contentVersion();
  writeFileSync(new URL('sw.js', ROOT), swSource(version));
  return version;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  console.log(`sw.js version ${stampServiceWorker()}`);
}
